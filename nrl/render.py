"""Render the structured model to the EXACT bytes both tools consume.

Three files per router, and these files ARE the artifact of record:

    interfaces   -> bind-mounted into the container; also embedded verbatim in
                    the Batfish snapshot
    frr.conf     -> bind-mounted to /etc/frr/frr.conf; also embedded verbatim
    daemons      -> bind-mounted to /etc/frr/daemons

Nothing downstream re-derives configuration from anything else. If a byte is
not in one of these files, neither tool sees it.
"""

from __future__ import annotations

from .model import Device, Scenario

# Must match FRR_IMAGE in nrl/emit.py. Batfish only needs the line to
# START with "frr version", but an artifact that claims a version it is
# not running is exactly the quiet inaccuracy this project exists to
# measure. Keep them in step.
FRR_VERSION = "8.4.1"

# The subset of ifupdown syntax we emit, and that bin/apply-interfaces.sh
# understands. Keep these two in sync -- the whole same-artifact argument rests
# on the container and Batfish agreeing about this file.
# Batfish's cumulus_interfaces parser does NOT recognise `link-down yes`
# (confirmed 2026-08-25: parseWarning "This syntax is unrecognized"). Admin
# state is therefore represented ONLY by `shutdown` under `interface X` in
# frr.conf, which Batfish does model -- it propagated the down state to the
# peer interface -- and which zebra enforces inside the container. One
# construct, one representation, both tools.
IFACE_SUBSET = ("auto <name>", "iface <name>", "    address <a.b.c.d/len>",
                "    alias <text>")


def render_interfaces(dev: Device) -> str:
    out = ["# This file describes the network interfaces",
           "# generated by nrl -- do not hand-edit; edit the scenario model",
           ""]
    for i in dev.ifaces:
        if i.name == "lo":
            out += ["auto lo", "iface lo inet loopback"]
        else:
            out += [f"auto {i.name}", f"iface {i.name}"]
        for a in i.addresses:
            out.append(f"    address {a}")
        if i.alias:
            out.append(f"    alias {i.alias}")
        # admin state deliberately absent here -- see IFACE_SUBSET above
        out.append("")
    return "\n".join(out) + "\n"


def render_daemons(dev: Device) -> str:
    """Which FRR daemons start. A missing 'ospfd=yes' means 'router ospf' is
    accepted and does nothing -- a silent failure worth guarding against."""
    on = {"zebra", "ospfd", "staticd"}
    names = ["zebra", "bgpd", "ospfd", "ospf6d", "ripd", "ripngd", "isisd",
             "pimd", "ldpd", "nhrpd", "eigrpd", "babeld", "sharpd", "pbrd",
             "bfdd", "fabricd", "vrrpd", "pathd", "staticd"]
    out = ["# generated by nrl"]
    out += [f"{n}={'yes' if n in on else 'no'}" for n in names]
    out += ["", 'vtysh_enable=yes', 'zebra_options="  -A 127.0.0.1 -s 90000000"',
            'ospfd_options="  -A 127.0.0.1"', 'staticd_options="-A 127.0.0.1"', ""]
    return "\n".join(out)


def render_frr_conf(dev: Device) -> str:
    out = [f"frr version {FRR_VERSION}",
           "frr defaults traditional",
           f"hostname {dev.hostname}",
           "log syslog informational",
           "service integrated-vtysh-config",
           "!"]

    for i in dev.ifaces:
        lines = []
        if i.alias:
            lines.append(f" description {i.alias}")
        if i.ospf_area is not None:
            lines.append(f" ip ospf area {i.ospf_area}")
        if i.ospf_cost is not None:
            lines.append(f" ip ospf cost {i.ospf_cost}")
        if i.ospf_network:
            lines.append(f" ip ospf network {i.ospf_network}")
        if not i.up:
            lines.append(" shutdown")
        if lines:
            out.append(f"interface {i.name}")
            out += lines
            out.append("!")

    for name, entries in sorted(dev.access_lists.items()):
        for e in entries:
            out.append(f"access-list {name} {e}")
        out.append("!")

    for name, entries in sorted(dev.prefix_lists.items()):
        for e in sorted(entries, key=lambda x: x.seq):
            le = f" le {e.le}" if e.le is not None else ""
            out.append(f"ip prefix-list {name} seq {e.seq} {e.action} {e.prefix}{le}")
        out.append("!")

    for name, clauses in sorted(dev.route_maps.items()):
        for c in sorted(clauses, key=lambda x: x.seq):
            out.append(f"route-map {name} {c.action} {c.seq}")
            if c.match_prefix_list:
                out.append(f" match ip address prefix-list {c.match_prefix_list}")
            if c.set_metric is not None:
                out.append(f" set metric {c.set_metric}")
            out.append("!")

    for s in dev.statics:
        dist = f" {s.distance}" if s.distance is not None else ""
        out.append(f"ip route {s.prefix} {s.nexthop}{dist}")
    if dev.statics:
        out.append("!")

    if dev.ospf:
        out.append("router ospf")
        out.append(f" ospf router-id {dev.ospf.router_id}")
        for i in dev.ifaces:
            if i.ospf_area is not None and i.ospf_passive:
                out.append(f" passive-interface {i.name}")
        for r in dev.ospf.redistribute:
            out.append(f" redistribute {r}")
        if dev.ospf.distribute_list_in:
            out.append(f" distribute-list {dev.ospf.distribute_list_in} in")
        out.append("!")

    out += ["line vty", "!", ""]
    return "\n".join(out)


def render_host_setup(dev: Device) -> str:
    """Endpoint containers are traffic sources, not modelled devices."""
    out = ["#!/bin/sh", "# generated by nrl -- host endpoint setup", "set -e"]
    for i in dev.ifaces:
        for a in i.addresses:
            out.append(f"ip addr replace {a} dev {i.name} || true")
        out.append(f"ip link set {i.name} up || true")
    if dev.host_gateway:
        out.append(f"ip route replace default via {dev.host_gateway} || true")
    out.append("")
    return "\n".join(out)


def render_device(dev: Device):
    if dev.kind == "host":
        return {"setup.sh": render_host_setup(dev)}
    return {
        "interfaces": render_interfaces(dev),
        "frr.conf": render_frr_conf(dev),
        "daemons": render_daemons(dev),
    }


def render_scenario(sc: Scenario):
    return {n: render_device(d) for n, d in sorted(sc.devices.items())}
